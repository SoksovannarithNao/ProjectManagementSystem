    t_start DATE;
    t_due DATE;
    t_progress NUMERIC;
    subtask_titles TEXT[] := ARRAY[
        'Draft initial version', 'Get peer review', 'Write unit tests', 'Update documentation',
        'Verify on staging', 'Address review comments', 'Final polish', 'Set up test data'
    ];
    comment_pool TEXT[] := ARRAY[
        'Backend endpoint is ready for review.',
        'I''ve finished the UI for this, please take a look.',
        'Can you review this when you get a chance?',
        'This is blocked by the authentication issue on the API side.',
        'Fixed in the latest commit, ready for re-test.',
        'Good catch, updating now.',
        'Tested locally, works as expected.',
        'Let''s sync tomorrow to unblock this.',
        'Pushed a fix, please verify.',
        'Looks good, merging shortly.',
        'Ran into an edge case with empty input, investigating.',
        'Nice work on this one!'
    ];
    n_subtasks INT;
    n_comments INT;
    j INT;
    parent_cid BIGINT;
    new_cid BIGINT;
    author_id BIGINT;
    task_ids BIGINT[];
BEGIN
    FOR proj IN SELECT id, name, status AS proj_status, start_date, end_date, manager_id FROM projects ORDER BY id LOOP
        task_ids := ARRAY[]::BIGINT[];
        -- Only ACTIVE project_members whose account itself is ACTIVE — this
        -- is the exact pool the DB triggers allow for task_assignees.
        SELECT array_agg(pm.user_id) INTO member_ids
        FROM project_members pm JOIN users u ON u.id = pm.user_id
        WHERE pm.project_id = proj.id AND pm.status = 'ACTIVE' AND u.account_status = 'ACTIVE';

        creator_id := proj.manager_id;
        total_days := GREATEST(proj.end_date - proj.start_date, 7);

        FOR i IN 1..7 LOOP
            t_start := proj.start_date + floor(total_days * (i - 1) / 8.0)::int;
            t_due   := proj.start_date + floor(total_days * i / 8.0)::int;
            IF t_due <= t_start THEN t_due := t_start + 3; END IF;
            IF t_due > proj.end_date THEN t_due := proj.end_date; END IF;

            final_status := base_statuses[i];
            IF proj.proj_status = 'PLANNING' THEN
                final_status := 'TO_DO';
            ELSIF proj.proj_status = 'COMPLETED' THEN
                final_status := CASE WHEN i = 6 THEN 'CANCELLED' ELSE 'COMPLETED' END;
            END IF;

            t_progress := CASE final_status
                WHEN 'COMPLETED' THEN 100
                WHEN 'CANCELLED' THEN 0
                WHEN 'IN_REVIEW' THEN 85
                WHEN 'IN_PROGRESS' THEN 25 + floor(random() * 50)
                ELSE 0
            END;

            INSERT INTO tasks (project_id, title, description, priority, status, start_date, due_date, estimated_hours, progress, created_by)
            VALUES (
                proj.id,
                task_title_suffixes[i] || ' — ' || proj.name,
                'Seed task for ' || proj.name || ': ' || lower(task_title_suffixes[i]) || '.',
                base_priorities[i],
                final_status,
                t_start, t_due,
                (4 + floor(random() * 20))::numeric,
                t_progress,
                creator_id
            ) RETURNING id INTO task_id;
            task_ids[i] := task_id;

            IF member_ids IS NOT NULL AND array_length(member_ids, 1) > 0 AND i NOT IN (1, 7) THEN
                assignee_id := member_ids[1 + floor(random() * array_length(member_ids, 1))::int];
                INSERT INTO task_assignees (task_id, user_id) VALUES (task_id, assignee_id) ON CONFLICT DO NOTHING;
                IF i = 3 AND array_length(member_ids, 1) > 1 THEN
                    assignee_id := member_ids[1 + floor(random() * array_length(member_ids, 1))::int];
                    INSERT INTO task_assignees (task_id, user_id) VALUES (task_id, assignee_id) ON CONFLICT DO NOTHING;
                END IF;
            END IF;

            n_subtasks := 1 + floor(random() * 3)::int;
            FOR j IN 1..n_subtasks LOOP
                INSERT INTO subtasks (task_id, title, assignee_id, due_date, status)
                VALUES (
                    task_id,
                    subtask_titles[1 + floor(random() * array_length(subtask_titles, 1))::int],
                    CASE WHEN member_ids IS NOT NULL AND array_length(member_ids, 1) > 0 AND random() > 0.3
                         THEN member_ids[1 + floor(random() * array_length(member_ids, 1))::int] ELSE NULL END,
                    t_due - floor(random() * 5)::int,
                    -- A COMPLETED task's subtasks must themselves all be
                    -- COMPLETED (trg_tasks_not_completed_with_open_subtasks
                    -- would otherwise reject/self-heal this the moment
                    -- anything re-touches the row) — random status for every
                    -- other final_status, since only COMPLETED is gated.
                    CASE WHEN final_status = 'COMPLETED' THEN 'COMPLETED'
                         ELSE (ARRAY['TO_DO', 'IN_PROGRESS', 'COMPLETED'])[1 + floor(random() * 3)::int]
                    END
                );
            END LOOP;

            IF member_ids IS NOT NULL AND array_length(member_ids, 1) > 0 THEN
                n_comments := 1 + floor(random() * 3)::int;
                parent_cid := NULL;
                FOR j IN 1..n_comments LOOP
                    author_id := member_ids[1 + floor(random() * array_length(member_ids, 1))::int];
                    INSERT INTO comments (task_id, user_id, parent_comment_id, message)
                    VALUES (
                        task_id, author_id,
                        CASE WHEN j > 1 AND random() > 0.5 THEN parent_cid ELSE NULL END,
                        comment_pool[1 + floor(random() * array_length(comment_pool, 1))::int]
                    ) RETURNING id INTO new_cid;
                    parent_cid := new_cid;
                END LOOP;
            END IF;
        END LOOP;

        -- One dependency per project, for the "Blocked" state: task 7
        -- ("Documentation and handoff") depends on task 6 ("Fix reported
        -- defects"). Task 7 is always TO_DO (or, for a PLANNING project,
        -- every task is) — trg_task_dependencies_status_gate only rejects a
        -- new dependency when the dependent task is already
        -- IN_PROGRESS/IN_REVIEW/COMPLETED while the prerequisite isn't, so a
        -- TO_DO task 7 is always a safe side to attach this to regardless of
        -- task 6's status. Skipped for a COMPLETED project, where task 7 is
        -- COMPLETED and task 6 is CANCELLED (not COMPLETED) — exactly the
        -- combination that trigger exists to reject.
        IF proj.proj_status <> 'COMPLETED' THEN
            INSERT INTO task_dependencies (task_id, depends_on_task_id)
            VALUES (task_ids[7], task_ids[6])
            ON CONFLICT DO NOTHING;
        END IF;
    END LOOP;
END $$;

-- Force a handful of genuinely overdue tasks (due in the past, not
-- completed) for testing the overdue-detection view/notifications — only
-- within projects whose own end_date is safely still in the future, so
-- check_task_due_date_within_project can never fail. Excludes any task that
-- is the dependent side of a task_dependencies row (the "Blocked" task 7s
-- seeded above): forcing status = 'IN_PROGRESS' on one of those would trip
-- trg_tasks_dependencies_status_gate, since their prerequisite isn't
-- COMPLETED.
WITH candidates AS (
    SELECT t.id FROM tasks t JOIN projects p ON p.id = t.project_id
    WHERE p.status IN ('IN_PROGRESS', 'ON_HOLD') AND p.end_date >= CURRENT_DATE + 5
      AND t.id NOT IN (SELECT task_id FROM task_dependencies)
    ORDER BY t.id
    LIMIT 8
)
UPDATE tasks SET
    due_date = CURRENT_DATE - (2 + floor(random() * 8))::int,
    start_date = LEAST(start_date, CURRENT_DATE - 20),
    status = 'IN_PROGRESS',
    progress = 30 + floor(random() * 40)
WHERE id IN (SELECT id FROM candidates);

